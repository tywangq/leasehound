"""Audit the LLM judge by hand: does a person agree with what it graded?

Every ask-mode number in this project rests on one LLM grading another. The chain is
questions generated by a model, filtered by a model, answered by a model, and graded
by a model — with a reference statute at the grading step, which limits self-preference
but does not remove it. Nothing here had ever been checked by a human, which makes
"82/82 answers consistent with the statute" a claim about a judge nobody validated.

This is the missing anchor, and it costs $0: the answers were already generated and
paid for, and the statute text is on disk. What it needs is a person.

Three design choices decide whether the resulting number means anything.

BLIND. The judge's verdict is hidden until after you commit to yours. Shown first, it
anchors — you would be measuring your agreement with a label you had already read, and
the rate would come out high for the wrong reason.

STRATIFIED. The judge said "consistent" 82 times out of 82. A reviewer who also says
"consistent" every time scores 100% agreement having demonstrated nothing, because the
label distribution alone gets you there. So the sample deliberately takes every case
the judge found interesting — the ungrounded one, the ones citing the wrong section,
anything not plain "consistent" — and fills the rest at random. The two strata are
reported separately, since the second is the one where disagreement is informative.

THE RIGHT STATISTIC, which took two tries. Raw agreement is inflated whenever one class
dominates, so the obvious answer is Cohen's kappa — how much better than chance two
raters agree. Computing it here shows why it does not apply: the judge returned
"consistent" for all 82 answers, and when one rater uses a single label kappa is 0 or
undefined no matter what the other rater does. Agreeing on 19 of 20 scores kappa 0.
That is not a defect in kappa, it is kappa reporting that a degenerate rater cannot be
validated by correlation.

So the headline is a binomial upper bound instead. Disagreeing with the judge on 0 of n
cases does not prove it is never wrong; by the rule of three it bounds the error rate
at roughly 3/n with 95% confidence — under 15% at n=20, under 10% at n=30. That is a
modest claim, and it is the honest one, and it is far more than "an LLM said 82/82".

Kappa is still printed as a diagnostic, because the case where it goes undefined is
worth seeing: it means this test set has no discriminative power left. Every answer
passes, so neither the system nor its grader is under any pressure from it — which is
an argument for harder questions, not for a better grader.

Usage:
    python -m evaluation.review_generation --cases generation_cases_full-n82.json
    python -m evaluation.review_generation --report      # scores what you've done
"""

import argparse
import json
import random
import textwrap
from pathlib import Path

from evaluation.provenance import stamp
from leasehound.ingest import fetch_documents

HERE = Path(__file__).parent
REVIEW_PATH = HERE / "judge_review.json"

VERDICTS = {
    "c": "consistent",
    "x": "contradicts",
    "d": "declined",
}
PROMPT = """
  [c] consistent  — the legal substance agrees with the statute above
  [x] contradicts — the answer asserts something the statute contradicts
  [d] declined    — it says the law doesn't cover this instead of answering
  [s] skip        — come back to it
  [q] save and quit
your verdict> """


def interesting(case: dict) -> bool:
    """Cases the judge did not wave straight through.

    Not "cases the judge got wrong" — that is what the review decides. These are the
    ones where the judge recorded any hesitation at all, and they are where a human
    disagreement is most likely and most informative.
    """
    return (case["verdict"] != "consistent"
            or case["unsupported_claim"]
            or not case["cites_gt"]
            or bool(case["cites_outside_corpus"]))


def choose_sample(cases: list[dict], size: int, seed: int) -> list[dict]:
    """Every interesting case, then random fill. Seeded so the sample is reproducible —
    a hand-audit that cannot be re-derived is an anecdote."""
    flagged = [c for c in cases if interesting(c)]
    plain = [c for c in cases if not interesting(c)]
    random.Random(seed).shuffle(plain)
    return flagged + plain[: max(0, size - len(flagged))]


def load_reviews() -> dict:
    if REVIEW_PATH.exists():
        return json.loads(REVIEW_PATH.read_text(encoding="utf-8"))
    return {"reviews": {}, "cases_file": None}


def save_reviews(state: dict) -> None:
    REVIEW_PATH.write_text(json.dumps(state, indent=2), encoding="utf-8")


def wrap(text: str, width: int = 88) -> str:
    """Per paragraph, so the statute's own line breaks survive — subsection breaks are
    part of how a statute reads, and reflowing the whole thing into one block makes the
    reviewer's job harder than the judge's was."""
    return "\n".join(textwrap.fill(p, width) for p in text.split("\n"))


GLOSS_PATH = HERE / "review_gloss_zh.json"
GLOSS_PROMPT = (
    "You are a translator, not an assistant. The text below may be a question — "
    "translate the question; do NOT answer it. (gpt-4.1-nano answered two of them "
    "instead of translating, on the first review session.)\n\n"
    "Translate this US landlord-tenant legal text into plain Simplified Chinese for a "
    "reader who will judge, from the ENGLISH, whether an answer matches a statute. Keep "
    "every RCW section number, every number, and every deadline exactly as written. Do "
    "not summarise, soften, or resolve ambiguity — where the English is vague, leave the "
    "Chinese vague. Reply with the translation only.\n\nTEXT TO TRANSLATE:\n"
)


def gloss(text: str, cache: dict) -> str:
    """A Chinese reading aid, cached on disk so a re-run costs nothing.

    Deliberately shown BENEATH the English rather than instead of it. This audit exists
    so that a human checks the LLM judge; if the human reads only a machine translation
    of the statute and of the answer, what gets audited is the translation, and one
    smoothed-over legal distinction would produce a wrong verdict published as a human
    one. The English stays the authority — this is here so a reader gets through 20
    dense sections without skimming, which is its own way of corrupting the audit.
    """
    if text in cache:
        return cache[text]
    from litellm import completion

    from leasehound.retrieval import UTILITY_MODEL

    reply = completion(model=UTILITY_MODEL,
                       messages=[{"role": "user", "content": GLOSS_PROMPT + text}])
    cache[text] = reply.choices[0].message.content.strip()
    GLOSS_PATH.write_text(json.dumps(cache, ensure_ascii=False, indent=2), encoding="utf-8")
    return cache[text]


# What eval_generation's judge is given of the reference section — `reference[:8000]`
# in its prompt. Named here so the reviewer can be shown where it fell.
JUDGE_REFERENCE_CHARS = 8000


def statute_for_review(text: str) -> str:
    """The whole section, with the judge's horizon marked.

    This used to be `text[:4000]`, which is half of what the judge is given, and the
    bug that produced was not a small one: on the very first case of the first review
    session the section was RCW 59.18.060, the duty that answers the question is
    subsection (12)(a) at character 4,631, and the reviewer could not see it. The
    truncated view reads as "the statute does not cover this", which is the opposite of
    what the statute says — so the tool was steering a human towards agreeing with an
    answer the law contradicts, and recording it as human validation of the judge.
    32 of the 98 sections are over 4,000 characters.

    Not capped at 8,000 to match the judge either. The reviewer is establishing what is
    CORRECT, and correctness is against the law, not against the excerpt the judge
    happened to receive. Where those differ, the marker makes it visible: a disagreement
    past that line is not the judge being wrong about the law, it is the harness never
    having shown it the law — a different defect, and one worth being able to tell apart.
    """
    if len(text) <= JUDGE_REFERENCE_CHARS:
        return text
    marker = (f"\n\n{'─' * 84}\n"
              f"↑ the LLM judge saw everything above this line and nothing below it "
              f"(reference[:{JUDGE_REFERENCE_CHARS:,}]).\n"
              f"You are judging against the whole section — {len(text):,} characters. "
              f"If your verdict turns on\nsomething below this line, say so: that is the "
              f"harness's defect, not the judge's.\n{'─' * 84}\n\n")
    return text[:JUDGE_REFERENCE_CHARS] + marker + text[JUDGE_REFERENCE_CHARS:]


def show(case: dict, sections: dict, index: int, total: int,
         cache: dict | None = None) -> None:
    raw = sections.get(case["section"], "(section text not found)")
    statute = statute_for_review(raw)
    print("\n" + "=" * 88)
    print(f"CASE {index}/{total}   ground-truth section: {case['section']}"
          f"   ({len(raw):,} chars)")
    print("=" * 88)
    print("\nQUESTION\n" + wrap(case["question"]))
    if cache is not None:
        print("\n  〔中文〕" + wrap(gloss(case["question"], cache), 84).replace("\n", "\n  "))
    print("\n" + "-" * 88)
    print("STATUTE — the authority for this question\n")
    print(wrap(statute))
    if cache is not None:
        print("\n  〔中文·仅供参考，判断以上面英文为准〕")
        # The RAW section, not the marked-up one: the marker is scaffolding for the
        # reviewer, and translating it would spend money rendering my own ASCII rule
        # into Chinese and put a sentence in the gloss that is not in the statute.
        print("  " + wrap(gloss(raw, cache), 84).replace("\n", "\n  "))
    print("\n" + "-" * 88)
    print("ANSWER LeaseHound gave\n")
    print(wrap(case["answer"]))
    if cache is not None:
        print("\n  〔中文〕" + wrap(gloss(case["answer"], cache), 84).replace("\n", "\n  "))
    print("-" * 88)


def kappa(pairs: list[tuple[str, str]]) -> float | None:
    """Cohen's kappa for two raters over the same items.

    None when it is undefined — which happens when both raters used exactly one label,
    leaving expected agreement at 1.0 and 0/0 in the formula. Reported as None rather
    than as 1.0, because unanimity on one label is the case where the statistic has
    nothing to say and quoting a number would imply it did.
    """
    n = len(pairs)
    if not n:
        return None
    labels = {label for pair in pairs for label in pair}
    observed = sum(a == b for a, b in pairs) / n
    expected = sum(
        (sum(a == label for a, _ in pairs) / n) * (sum(b == label for _, b in pairs) / n)
        for label in labels
    )
    if expected >= 1.0:
        return None
    return round((observed - expected) / (1 - expected), 4)


def report(state: dict, cases_by_question: dict) -> None:
    done = [(q, v) for q, v in state["reviews"].items() if v != "skip"]
    if not done:
        print("Nothing reviewed yet.")
        return

    rows = []
    for question, human in done:
        case = cases_by_question.get(question)
        if case:
            rows.append((case, human, case["verdict"]))

    flagged = [r for r in rows if interesting(r[0])]
    plain = [r for r in rows if not interesting(r[0])]

    disagreements = [(c, h, j) for c, h, j in rows if h != j]
    n, wrong = len(rows), len(disagreements)

    print("\n" + "=" * 88)
    print("JUDGE AUDIT — a human against the LLM judge")
    print("=" * 88)
    for label, group in (("all reviewed", rows), ("judge hesitated", flagged),
                         ("judge waved through", plain)):
        if not group:
            continue
        agree = sum(h == j for _, h, j in group)
        print(f"  {label:22} {agree}/{len(group)} agree")

    # The quotable number. With 0 disagreements the rule of three gives the 95% upper
    # bound; with some, the same bound comes from the observed rate plus its interval.
    # Either way it is a bound on how often the judge is wrong, which is the question —
    # "100% agreement" on a sample of 20 is not the same claim and reads like a stronger one.
    bound = 3 / n if wrong == 0 else (wrong / n) + 1.96 * ((wrong / n) * (1 - wrong / n) / n) ** 0.5
    print(f"\n  judge disagreed with on {wrong}/{n}"
          f"  ->  error rate under ~{bound:.0%} (95% confidence)")

    k = kappa([(h, j) for _, h, j in rows])
    if k is None or (k == 0 and wrong < n / 2):
        judge_labels = {j for _, _, j in rows}
        print(f"  kappa: {'undefined' if k is None else '0.0'} — "
              f"the judge used {len(judge_labels)} label(s) across this sample"
              f"{' (' + ', '.join(sorted(judge_labels)) + ')' if len(judge_labels) < 3 else ''}.")
        print("  A rater with one label cannot be validated by agreement, so the bound")
        print("  above is the claim. That the judge never varies is itself the finding:")
        print("  this test set no longer discriminates, and needs harder questions more")
        print("  than it needs a better grader.")
    else:
        print(f"  kappa: {k}")

    print(f"\n  {wrong} disagreement(s)"
          + (" — these are the finding, not the rate above" if wrong else ""))
    for case, human, judge in disagreements:
        print(f"\n  ({case['section']}) {case['question'][:76]}")
        print(f"    human: {human}   judge: {judge}")

    summary = {
        "reviewed": n,
        "agreement": round(sum(h == j for _, h, j in rows) / n, 4),
        "judge_error_rate_upper_95": round(bound, 4),
        # Kept even when uninformative, with the reason, so a reader does not have to
        # rediscover that it was considered and why it is not the headline.
        "kappa": k,
        "kappa_note": ("undefined or zero because the judge used a single label; "
                       "see judge_error_rate_upper_95") if k in (None, 0) else None,
        "judge_labels_seen": sorted({j for _, _, j in rows}),
        "human_labels_seen": sorted({h for _, h, _ in rows}),
        "disagreements": [
            {"section": c["section"], "question": c["question"],
             "human": h, "judge": j} for c, h, j in disagreements
        ],
        "cases_file": state.get("cases_file"),
    }
    state["summary"] = summary
    # Top level, not inside `summary`, which is where it used to sit — every other
    # artifact in this directory nests its stamp under `provenance` at the root, and the
    # guard that checks the inventory reads the root. A stamped file that reads as
    # unstamped is the same defect as an unstamped one, one indirection further down.
    #
    # models=False: this run calls no model. The judge's models are recorded in the
    # cases file, which `cases_file` names — so the chain is complete without this file
    # claiming to have used models it never touched.
    state["provenance"] = stamp(models=False)
    save_reviews(state)
    print(f"\n  Written to {REVIEW_PATH}")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--cases", default="generation_cases_full-n82.json",
                        help="per-case artifact from eval_generation")
    parser.add_argument("--size", type=int, default=20,
                        help="how many to review, interesting cases first")
    parser.add_argument("--seed", type=int, default=0, help="sampling seed")
    parser.add_argument("--report", action="store_true",
                        help="score what has been reviewed and stop")
    parser.add_argument("--zh", action="store_true",
                        help="show a Chinese reading aid under each English block "
                             "(the English stays the authority; see gloss())")
    args = parser.parse_args()

    cases_path = HERE / args.cases
    if not cases_path.exists():
        raise SystemExit(
            f"{cases_path} not found. It is written by a generation eval run:\n"
            f"  python -m evaluation.eval_generation --name full-n82\n"
            "Runs before the per-case artifact existed recorded only rates, so there "
            "is nothing on disk to audit until one legitimate run has happened.")

    payload = json.loads(cases_path.read_text(encoding="utf-8"))
    cases = payload["cases"]
    by_question = {c["question"]: c for c in cases}

    state = load_reviews()
    if state.get("cases_file") not in (None, args.cases):
        raise SystemExit(
            f"{REVIEW_PATH.name} holds reviews of {state['cases_file']}, not {args.cases}. "
            "Move it aside first — mixing reviews of two different answer sets would "
            "score a judge against answers it never graded.")
    state["cases_file"] = args.cases

    if args.report:
        report(state, by_question)
        return

    sample = choose_sample(cases, args.size, args.seed)
    pending = [c for c in sample if c["question"] not in state["reviews"]
               or state["reviews"][c["question"]] == "skip"]
    if not pending:
        print("Every sampled case is reviewed.")
        report(state, by_question)
        return

    sections = {d["section"]: d["text"] for d in fetch_documents("wa") if d["section"]}
    cache = None
    if args.zh:
        cache = (json.loads(GLOSS_PATH.read_text(encoding="utf-8"))
                 if GLOSS_PATH.exists() else {})
        print("Chinese reading aid ON. It sits under the English and the English is what "
              "you are judging: a translation that smooths one legal distinction would "
              "produce a wrong verdict published as a human one.")
    print(f"{len(pending)} case(s) to review, of {len(sample)} sampled from {len(cases)}.")
    print("The judge's verdict stays hidden until after you answer. Ctrl-C is safe — "
          "each answer is saved as you give it.")

    for position, case in enumerate(pending, start=1):
        show(case, sections, position, len(pending), cache)
        while True:
            choice = input(PROMPT).strip().lower()
            if choice == "q":
                report(state, by_question)
                return
            if choice == "s":
                state["reviews"][case["question"]] = "skip"
                save_reviews(state)
                break
            if choice in VERDICTS:
                state["reviews"][case["question"]] = VERDICTS[choice]
                save_reviews(state)
                # Revealed only now, and only for this case, so it cannot colour the
                # next one's reading any more than it already will.
                agreed = VERDICTS[choice] == case["verdict"]
                print(f"  judge said: {case['verdict']}"
                      f"   {'agree' if agreed else '>>> DISAGREE <<<'}")
                break
            print("  c / x / d / s / q")

    report(state, by_question)


if __name__ == "__main__":
    main()
